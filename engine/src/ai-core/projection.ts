function productSkillRoots(coreRoot: string): string[] {
  return readdirSync(join(coreRoot, "skills"), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => join(coreRoot, "skills", entry.name))
    .filter((skillRoot) => {
      try {
        return statSync(join(skillRoot, "skill.yaml")).isFile();
      } catch {
        return false;
      }
    })
    .sort();
}

type WorkflowSummary = {
  id: string;
  entrySkill: string;
  uses: string[];
  prompts: string[];
};

function parseWorkflowStepReferences(text: string): { uses: string[]; prompts: string[] } {
  const uses: string[] = [];
  const prompts: string[] = [];
  let inSteps = false;
  for (const raw of text.split(/\r?\n/)) {
    if (raw === "steps:") {
      inSteps = true;
      continue;
    }
    if (!inSteps) continue;
    if (raw.length > 0 && !/^\s/.test(raw)) {
      inSteps = false;
      continue;
    }
    const trimmed = raw.trim();
    if (trimmed.startsWith("uses:")) {
      uses.push(trimmed.slice("uses:".length).trim());
    } else if (trimmed.startsWith("prompt:")) {
      prompts.push(trimmed.slice("prompt:".length).trim());
    }
  }
  return { uses, prompts };
}

function loadWorkflowSummaries(coreRoot: string): WorkflowSummary[] {
  const dir = join(coreRoot, "workflows");
  const summaries: WorkflowSummary[] = [];
  let files: string[];
  try {
    files = readdirSync(dir)
      .filter((f) => f.endsWith(".workflow.yaml"))
      .sort();
  } catch {
    return summaries;
  }
  for (const file of files) {
    const text = readFileSync(join(dir, file), "utf8");
    const path = `.ai/core/workflows/${file}`;
    const top = parseYamlTopLevelScalars(text, path);
    if (!top.ok) continue;
    const fields = top.value ?? {};
    const id = fields.id ?? "";
    const entrySkill = fields.entry_skill ?? "";
    const { uses, prompts } = parseWorkflowStepReferences(text);
    summaries.push({ id, entrySkill, uses, prompts });
  }
  return summaries;
}

function stripSkillVersion(idWithVersion: string): string {
  return idWithVersion.replace(/@\d+$/, "");
}

function pushUnique(target: string[], value: string): void {
  if (!target.includes(value)) target.push(value);
}

function buildCallGraph(
  coreRoot: string,
  commands: CommandContract[],
): Map<string, SkillCallGraph> {
  const graphs = new Map<string, SkillCallGraph>();

  function ensure(skillName: string): SkillCallGraph {
    let graph = graphs.get(skillName);
    if (!graph) {
      graph = {
        upstreamCommands: [],
        downstreamWorkflows: [],
        downstreamAgents: [],
        downstreamPlugins: [],
        downstreamPrompts: [],
      };
      graphs.set(skillName, graph);
    }
    return graph;
  }

  for (const cmd of commands) {
    const skillName = stripSkillVersion(cmd.skill);
    pushUnique(ensure(skillName).upstreamCommands, cmd.id);
  }

  for (const workflow of loadWorkflowSummaries(coreRoot)) {
    const skillName = stripSkillVersion(workflow.entrySkill);
    if (!skillName) continue;
    const graph = ensure(skillName);
    pushUnique(graph.downstreamWorkflows, workflow.id);
    for (const reference of workflow.uses) {
      if (reference.startsWith("agent:")) {
        pushUnique(graph.downstreamAgents, reference.slice("agent:".length));
      } else if (reference.startsWith("plugin:")) {
        pushUnique(graph.downstreamPlugins, reference.slice("plugin:".length));
      }
    }
    for (const prompt of workflow.prompts) {
      pushUnique(graph.downstreamPrompts, prompt);
    }
  }

  return graphs;
}

