function renderRuntimeIndex(
  runtime: ProjectionRuntime,
  coreRoot: string,
): { path: string; content: string } | undefined {
  const commandsResult = loadCommandContracts(coreRoot);
  if (!commandsResult.ok) return undefined;
  const commands = commandsResult.value ?? [];
  const callGraphs = buildCallGraph(coreRoot, commands);
  const entries = buildIndexEntries(coreRoot, commands, callGraphs);
  return { path: indexDocPath(runtime), content: renderIndexDoc(entries) };
}

function renderSkills(
  runtime: ProjectionRuntime,
  coreRoot: string,
): AiCoreResult<RenderedSkillFile[]> {
  const files: RenderedSkillFile[] = [];
  const issues: AiCoreIssue[] = [];
  const callGraphs = buildCallGraph(coreRoot, loadAllCommandContracts(coreRoot));
  for (const skillRoot of productSkillRoots(coreRoot)) {
    const skillSource = readFileSync(join(skillRoot, "skill.yaml"), "utf8");
    const skillName = relative(coreRoot, skillRoot).split("/").pop() ?? "";
    const result = renderProductSkill({
      runtime,
      skillRoot,
      repoRelativeSkillRoot: `.ai/core/${relative(coreRoot, skillRoot)}`,
      generatedHeader: generatedHeader(skillSource),
      callGraph: callGraphs.get(skillName),
    });
    if (result.ok) files.push(...(result.value ?? []));
    else issues.push(...result.issues);
  }
  if (issues.length > 0) return { ok: false, issues };
  return { ok: true, value: files, issues: [] };
}

