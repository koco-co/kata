function deletedInventoryRows(
  coreRoot: string,
  runtime: ProjectionRuntime,
): ProjectionInventoryRow[] {
  const inventory = parseProjectionInventory(
    readFileSync(join(coreRoot, "runtimes/projection-inventory.yaml"), "utf8"),
  );
  return inventory.filter((row) => row.runtime === runtime && row.disposition === "deleted");
}

function deletedInventoryPaths(coreRoot: string, runtime: ProjectionRuntime): string[] {
  return deletedInventoryRows(coreRoot, runtime).map((row) => row.path);
}

function walkRuntimeVendorFiles(root: string, displayRoot = root): string[] {
  const files: string[] = [];
  let entries: string[];
  try {
    entries = readdirSync(root).sort();
  } catch {
    return files;
  }
  for (const entry of entries) {
    const fullPath = join(root, entry);
    const stat = lstatSync(fullPath).isSymbolicLink() ? lstatSync(fullPath) : statSync(fullPath);
    if (stat.isDirectory()) files.push(...walkRuntimeVendorFiles(fullPath, displayRoot));
    if (stat.isFile() || stat.isSymbolicLink()) files.push(relative(displayRoot, fullPath));
  }
  return files;
}

function copiedVendorExtraIssues(
  root: string,
  runtime: ProjectionRuntime,
  vendorFiles: VendorManifestFile[],
): AiCoreIssue[] {
  const issues: AiCoreIssue[] = [];
  const targetRoot = dirname(skillProjectionPath(runtime, "playwright-cli"));
  const expected = new Set(vendorFiles.map((file) => file.path));
  for (const filePath of walkRuntimeVendorFiles(join(root, targetRoot))) {
    if (expected.has(filePath)) continue;
    issues.push({
      code: "projection.drift",
      severity: "error",
      message: "Copied vendor projection contains an unmanifested file.",
      path: join(targetRoot, filePath),
    });
  }
  return issues;
}

function copiedVendorRootIssue(root: string, runtime: ProjectionRuntime): AiCoreIssue | undefined {
  const targetRoot = dirname(skillProjectionPath(runtime, "playwright-cli"));
  const pathIssue = projectionVendorPathComponentIssue(root, runtime);
  if (pathIssue) return pathIssue;
  try {
    if (lstatSync(join(root, targetRoot)).isSymbolicLink()) {
      return {
        code: "projection.drift",
        severity: "error",
        message: "Copied vendor runtime skill root must not be a symlink.",
        path: targetRoot,
      };
    }
  } catch {
    return undefined;
  }
  return undefined;
}

function projectionVendorPathComponentIssue(
  root: string,
  runtime: ProjectionRuntime,
): AiCoreIssue | undefined {
  return symlinkPathComponentIssue({
    root,
    relativePath: dirname(skillProjectionPath(runtime, "playwright-cli")),
    code: "projection.drift",
    message: "Projection runtime vendor paths must not contain symlink components.",
  });
}

function projectionTargetPathIssue(root: string, relativePath: string): AiCoreIssue | undefined {
  const absoluteRoot = resolve(root);
  const absoluteTarget = resolve(absoluteRoot, relativePath);
  const targetRelativeToRoot = relative(absoluteRoot, absoluteTarget);
  if (
    targetRelativeToRoot === "" ||
    targetRelativeToRoot.startsWith("..") ||
    isAbsolute(targetRelativeToRoot)
  ) {
    return {
      code: "projection.drift",
      severity: "error",
      message: "Projection target path must stay under output root.",
      path: relativePath,
    };
  }
  return symlinkPathComponentIssue({
    root,
    relativePath,
    code: "projection.drift",
    message: "Projection target paths must not contain symlink components.",
  });
}

function pruneProjectionFile(root: string, relativePath: string): AiCoreIssue | undefined {
  const issue = projectionTargetPathIssue(root, relativePath);
  if (issue) return issue;
  const fullPath = join(root, relativePath);
  if (!existsSync(fullPath)) return undefined;
  if (lstatSync(fullPath).isDirectory()) {
    return {
      code: "projection.deleted_path_directory",
      severity: "error",
      message: "Deleted projection inventory paths must point to files, not directories.",
      path: relativePath,
    };
  }
  rmSync(fullPath, { force: true });
  return undefined;
}

function pruneDeletedRowIssues(row: ProjectionInventoryRow): AiCoreIssue[] {
  const issues: AiCoreIssue[] = [];
  if (!row.source || !row.reason) {
    issues.push({
      code: "projection.deleted_missing_metadata",
      severity: "error",
      message: "Deleted rows require source and reason before pruning.",
      path: row.path,
    });
  }
  if (!isExplicitRuntimeFilePath(row.path)) {
    issues.push({
      code: "projection.deleted_not_file_path",
      severity: "error",
      message: "Deleted rows must point to explicit runtime files before pruning.",
      path: row.path,
    });
  }
  return issues;
}

function isExplicitRuntimeFilePath(path: string): boolean {
  const fileName = path.split("/").filter(Boolean).at(-1) ?? "";
  return fileName.includes(".");
}

function deletedFilePresentIssues(
  root: string,
  coreRoot: string,
  runtime: ProjectionRuntime,
): AiCoreIssue[] {
  const issues: AiCoreIssue[] = [];
  for (const path of deletedInventoryPaths(coreRoot, runtime)) {
    const pathIssue = projectionTargetPathIssue(root, path);
    if (pathIssue) {
      issues.push(pathIssue);
      continue;
    }
    if (!existsSync(join(root, path))) continue;
    issues.push({
      code: "projection.deleted_file_present",
      severity: "error",
      message: "Runtime file is present but projection inventory marks it deleted.",
      path,
    });
  }
  return issues;
}

function writeProjectionFile(
  root: string,
  file: { path: string; content: string | Buffer },
): AiCoreIssue | undefined {
  const issue = projectionTargetPathIssue(root, file.path);
  if (issue) return issue;
  const fullPath = join(root, file.path);
  mkdirSync(dirname(fullPath), { recursive: true });
  writeFileSync(fullPath, file.content);
  return undefined;
}

function checkProjectionContracts(
  coreRoot: string,
  selectedRuntimes: ProjectionRuntime[],
  vendorFiles?: VendorManifestFile[],
): AiCoreIssue[] {
  const issues: AiCoreIssue[] = [];
  const selected = new Set<ProjectionRuntime>(selectedRuntimes);
  const generatedByRuntime = new Map<ProjectionRuntime, RenderedSkillFile[]>();
  for (const runtime of selectedRuntimes) {
    const rendered = renderSkills(runtime, coreRoot);
    if (rendered.ok) generatedByRuntime.set(runtime, rendered.value ?? []);
    else issues.push(...rendered.issues);
  }
  const actualGeneratedPaths = selectedRuntimes.flatMap((runtime) => [
    ...(generatedByRuntime.get(runtime) ?? []).map((file) => file.path),
    rootRuntimeDocPath(runtime),
    indexDocPath(runtime),
  ]);
  const inventoryPath = join(coreRoot, "runtimes/projection-inventory.yaml");
  const inventoryResult = parseProjectionInventoryText(
    readFileSync(inventoryPath, "utf8"),
    ".ai/core/runtimes/projection-inventory.yaml",
  );
  if (!inventoryResult.ok) return [...issues, ...inventoryResult.issues];
  const inventory = inventoryResult.value ?? [];
  const inventoryGeneratedPaths = inventory
    .filter((row) => row.disposition === "generated" && selected.has(row.runtime))
    .map((row) => row.path);
  if (!sameStringSet(inventoryGeneratedPaths, actualGeneratedPaths)) {
    issues.push({
      code: "projection.inventory_mismatch",
      severity: "error",
      message: "Projection inventory generated files do not match renderer output.",
      path: ".ai/core/runtimes/projection-inventory.yaml",
    });
  }
  if (vendorFiles) {
    const actualCopiedVendorPaths = selectedRuntimes.flatMap((runtime) =>
      renderedCopiedVendorPaths(runtime, vendorFiles),
    );
    const inventoryCopiedVendorRows = inventory.filter(
      (row) => row.disposition === "copied_vendor" && selected.has(row.runtime),
    );
    const inventoryCopiedVendorPaths = inventoryCopiedVendorRows.map((row) => row.path);
    if (!sameStringSet(inventoryCopiedVendorPaths, actualCopiedVendorPaths)) {
      issues.push({
        code: "projection.inventory_mismatch",
        severity: "error",
        message: "Projection inventory copied vendor files do not match renderer output.",
        path: ".ai/core/runtimes/projection-inventory.yaml",
      });
    }
    const expectedSources = new Map<string, string>();
    for (const runtime of selectedRuntimes) {
      const targetRoot = dirname(skillProjectionPath(runtime, "playwright-cli"));
      for (const file of vendorFiles) {
        expectedSources.set(join(targetRoot, file.path), vendorSourcePath(file));
      }
    }
    if (inventoryCopiedVendorRows.some((row) => row.source !== expectedSources.get(row.path))) {
      issues.push({
        code: "projection.inventory_mismatch",
        severity: "error",
        message: "Projection inventory copied vendor source does not match frozen vendor artifact.",
        path: ".ai/core/runtimes/projection-inventory.yaml",
      });
    }
  }

  for (const runtime of selectedRuntimes) {
    const runtimePath = join(coreRoot, "runtimes", `${runtime}.yaml`);
    const runtimeContractPath = `.ai/core/runtimes/${runtime}.yaml`;
    const runtimeGeneratedFiles = parseYamlStringList(
      readFileSync(runtimePath, "utf8"),
      runtimeContractPath,
      "generated_files",
    );
    if (!runtimeGeneratedFiles.ok) {
      issues.push(...runtimeGeneratedFiles.issues);
      continue;
    }
    const runtimeRenderedGeneratedPaths = [
      ...(generatedByRuntime.get(runtime) ?? []).map((file) => file.path),
      rootRuntimeDocPath(runtime),
      indexDocPath(runtime),
    ];
    if (!sameStringSet(runtimeGeneratedFiles.value ?? [], runtimeRenderedGeneratedPaths)) {
      issues.push({
        code: "projection.runtime_mismatch",
        severity: "error",
        message: "Runtime generated_files do not match renderer output.",
        path: runtimeContractPath,
      });
    }
    if (vendorFiles) {
      const runtimeCopiedVendorFiles = parseYamlStringList(
        readFileSync(runtimePath, "utf8"),
        runtimeContractPath,
        "copied_vendor_files",
      );
      if (!runtimeCopiedVendorFiles.ok) {
        issues.push(...runtimeCopiedVendorFiles.issues);
        continue;
      }
      if (
        !sameStringSet(
          runtimeCopiedVendorFiles.value ?? [],
          renderedCopiedVendorPaths(runtime, vendorFiles),
        )
      ) {
        issues.push({
          code: "projection.runtime_mismatch",
          severity: "error",
          message: "Runtime copied_vendor_files do not match renderer output.",
          path: runtimeContractPath,
        });
      }
    }
  }
  return issues;
}

function _repoRootFromCoreRoot(coreRoot: string): string {
  return dirname(dirname(coreRoot));
}

function writeRootRuntimeDoc(
  root: string,
  runtime: ProjectionRuntime,
  commandIndexBlock: string,
  coreRoot: string,
): AiCoreIssue | undefined {
  const path = rootRuntimeDocPath(runtime);
  if (!isPermittedRuntimeDocSymlink(root, path)) {
    const pathIssue = projectionTargetPathIssue(root, path);
    if (pathIssue) return pathIssue;
  }
  const fullPath = join(root, path);
  const current = existsSync(fullPath) ? readFileSync(fullPath, "utf8") : undefined;
  const merged = mergeCommandIndexBlock(coreRoot, current, commandIndexBlock);
  if (!merged.ok) return { ...merged.issues[0], path };
  mkdirSync(dirname(fullPath), { recursive: true });
  writeFileSync(fullPath, merged.value ?? "");
  return undefined;
}

function checkRootRuntimeDoc(
  root: string,
  runtime: ProjectionRuntime,
  commandIndexBlock: string,
): AiCoreIssue[] {
  const path = rootRuntimeDocPath(runtime);
  if (!isPermittedRuntimeDocSymlink(root, path)) {
    const pathIssue = projectionTargetPathIssue(root, path);
    if (pathIssue) return [pathIssue];
  }
  let current: string;
  try {
    current = readFileSync(join(root, path), "utf8");
  } catch {
    return [
      {
        code: "projection.drift",
        severity: "error",
        message: "Generated command index block is missing.",
        path,
      },
    ];
  }
  const markerState = commandIndexMarkerState(current);
  if (!markerState.ok) {
    return [
      {
        code: "projection.drift",
        severity: "error",
        message: markerState.message,
        path,
      },
    ];
  }
  if (markerState.completeBlocks !== 1) {
    return [
      {
        code: "projection.drift",
        severity: "error",
        message: "Root runtime doc must contain exactly one complete command index block.",
        path,
      },
    ];
  }
  if (extractCommandIndexBlock(current) !== commandIndexBlock) {
    return [
      {
        code: "projection.drift",
        severity: "error",
        message: "Generated command index block is stale.",
        path,
      },
    ];
  }
  return [];
}

export async function renderProjection(options: ProjectionOptions): Promise<AiCoreResult<null>> {
  const root = options.outputRoot ?? repoRoot();
  const coreRoot = options.coreRoot ?? defaultCoreRoot();
  const vendorRoot = options.vendorRoot ?? defaultVendorRoot();
  const vendorFiles = await readVendorSkillManifestFiles({
    id: "playwright-cli",
    root: vendorRepoRoot(vendorRoot),
    coreRoot,
  });
  if (!vendorFiles.ok) return { ok: false, issues: vendorFiles.issues };
  const commands = loadCommandContracts(coreRoot);
  if (!commands.ok) return { ok: false, issues: commands.issues };
  const commandIndexBlock = renderCommandIndexBlock(commands.value ?? []);
  const generatedByRuntime = new Map<ProjectionRuntime, RenderedSkillFile[]>();
  const generatedIssues: AiCoreIssue[] = [];
  for (const runtime of runtimes(options.runtime)) {
    const rendered = renderSkills(runtime, coreRoot);
    if (rendered.ok) generatedByRuntime.set(runtime, rendered.value ?? []);
    else generatedIssues.push(...rendered.issues);
  }
  if (generatedIssues.length > 0) return { ok: false, issues: generatedIssues };
  const pathIssues = runtimes(options.runtime).flatMap((runtime) => {
    const issue = projectionVendorPathComponentIssue(root, runtime);
    return issue ? [issue] : [];
  });
  if (pathIssues.length > 0) return { ok: false, issues: pathIssues };
  for (const runtime of runtimes(options.runtime)) {
    for (const file of generatedByRuntime.get(runtime) ?? []) {
      const issue = writeProjectionFile(root, file);
      if (issue) return { ok: false, issues: [issue] };
    }
    const rootDocIssue = writeRootRuntimeDoc(root, runtime, commandIndexBlock, coreRoot);
    if (rootDocIssue) return { ok: false, issues: [rootDocIssue] };
    const indexFile = renderRuntimeIndex(runtime, coreRoot);
    if (indexFile) {
      const indexIssue = writeProjectionFile(root, indexFile);
      if (indexIssue) return { ok: false, issues: [indexIssue] };
    }
    const vendorRootPathIssue = projectionTargetPathIssue(
      root,
      dirname(skillProjectionPath(runtime, "playwright-cli")),
    );
    if (vendorRootPathIssue) return { ok: false, issues: [vendorRootPathIssue] };
    rmSync(join(root, dirname(skillProjectionPath(runtime, "playwright-cli"))), {
      recursive: true,
      force: true,
    });
    for (const file of renderVendorSkill(runtime, vendorRoot, vendorFiles.value ?? [])) {
      const issue = writeProjectionFile(root, file);
      if (issue) return { ok: false, issues: [issue] };
    }
    if (options.prune === true) {
      const deletedRows = deletedInventoryRows(coreRoot, runtime);
      const deletedRowIssues = deletedRows.flatMap((row) => pruneDeletedRowIssues(row));
      if (deletedRowIssues.length > 0) return { ok: false, issues: deletedRowIssues };
      for (const row of deletedRows) {
        const issue = pruneProjectionFile(root, row.path);
        if (issue) return { ok: false, issues: [issue] };
      }
    }
  }
  return { ok: true, value: null, issues: [] };
}

export async function checkProjection(options: ProjectionOptions): Promise<AiCoreResult<null>> {
  const root = options.outputRoot ?? repoRoot();
  const coreRoot = options.coreRoot ?? defaultCoreRoot();
  const selectedRuntimes = runtimes(options.runtime);
  const vendorRoot = options.vendorRoot ?? defaultVendorRoot();
  const vendorFiles = await readVendorSkillManifestFiles({
    id: "playwright-cli",
    root: vendorRepoRoot(vendorRoot),
    coreRoot,
  });
  const issues: AiCoreIssue[] = checkProjectionContracts(
    coreRoot,
    selectedRuntimes,
    vendorFiles.ok ? vendorFiles.value : undefined,
  );
  if (!vendorFiles.ok) issues.push(...vendorFiles.issues);
  const commands = loadCommandContracts(coreRoot);
  const commandIndexBlock = commands.ok ? renderCommandIndexBlock(commands.value ?? []) : undefined;
  if (!commands.ok) issues.push(...commands.issues);
  const generatedByRuntime = new Map<ProjectionRuntime, RenderedSkillFile[]>();
  for (const runtime of selectedRuntimes) {
    const rendered = renderSkills(runtime, coreRoot);
    if (rendered.ok) generatedByRuntime.set(runtime, rendered.value ?? []);
    else issues.push(...rendered.issues);
  }
  for (const runtime of selectedRuntimes) {
    issues.push(...deletedFilePresentIssues(root, coreRoot, runtime));
    const runtimePathIssue = projectionVendorPathComponentIssue(root, runtime);
    if (runtimePathIssue) {
      issues.push(runtimePathIssue);
      continue;
    }
    for (const file of generatedByRuntime.get(runtime) ?? []) {
      const pathIssue = projectionTargetPathIssue(root, file.path);
      if (pathIssue) {
        issues.push(pathIssue);
        continue;
      }
      const fullPath = join(root, file.path);
      let current: string;
      try {
        current = readFileSync(fullPath, "utf8");
      } catch {
        issues.push({
          code: "projection.drift",
          severity: "error",
          message: "Generated projection content is missing.",
          path: file.path,
        });
        continue;
      }
      if (current !== file.content) {
        issues.push({
          code: "projection.drift",
          severity: "error",
          message: "Generated projection content is stale.",
          path: file.path,
        });
      }
    }
    if (commandIndexBlock) issues.push(...checkRootRuntimeDoc(root, runtime, commandIndexBlock));
    const indexFile = renderRuntimeIndex(runtime, coreRoot);
    if (indexFile) {
      const indexPathIssue = projectionTargetPathIssue(root, indexFile.path);
      if (indexPathIssue) issues.push(indexPathIssue);
      else {
        try {
          const currentIndex = readFileSync(join(root, indexFile.path), "utf8");
          if (currentIndex !== indexFile.content) {
            issues.push({
              code: "projection.drift",
              severity: "error",
              message: "Generated projection content is stale.",
              path: indexFile.path,
            });
          }
        } catch {
          issues.push({
            code: "projection.drift",
            severity: "error",
            message: "Generated projection content is missing.",
            path: indexFile.path,
          });
        }
      }
    }
    if (!vendorFiles.ok) continue;
    const copiedVendorRoot = copiedVendorRootIssue(root, runtime);
    if (copiedVendorRoot) {
      issues.push(copiedVendorRoot);
      continue;
    }
    issues.push(...copiedVendorExtraIssues(root, runtime, vendorFiles.value ?? []));
    for (const file of renderVendorSkill(runtime, vendorRoot, vendorFiles.value ?? [])) {
      const fullPath = join(root, file.path);
      let current: Buffer;
      try {
        if (lstatSync(fullPath).isSymbolicLink()) {
          issues.push({
            code: "projection.drift",
            severity: "error",
            message: "Copied vendor projection content must not be a symlink.",
            path: file.path,
          });
          continue;
        }
        const pathIssue = projectionTargetPathIssue(root, file.path);
        if (pathIssue) {
          issues.push(pathIssue);
          continue;
        }
        current = readFileSync(fullPath);
      } catch {
        issues.push({
          code: "projection.drift",
          severity: "error",
          message: "Copied vendor projection content is missing.",
          path: file.path,
        });
        continue;
      }
      if (!current.equals(file.content)) {
        issues.push({
          code: "projection.drift",
          severity: "error",
          message: "Copied vendor projection content is stale.",
          path: file.path,
        });
      }
    }
  }
  return { ok: issues.length === 0, value: null, issues };
}
