function loadCommandContracts(coreRoot: string): AiCoreResult<CommandContract[]> {
  const commandsRoot = join(coreRoot, "commands");
  const issues: AiCoreIssue[] = [];
  let files: string[];
  try {
    files = readdirSync(commandsRoot)
      .filter((file) => file.endsWith(".command.yaml"))
      .sort();
  } catch {
    return {
      ok: false,
      issues: [
        {
          code: "projection.contract_invalid",
          severity: "error",
          message: "Command contracts directory is missing.",
          path: ".ai/core/commands",
        },
      ],
    };
  }
  const commands: CommandContract[] = [];
  const seenIds = new Set<string>();
  for (const file of files) {
    const source = readFileSync(join(commandsRoot, file), "utf8");
    const path = `.ai/core/commands/${file}`;
    const contract = parseYamlContract(source, path);
    const contractIssues = yamlIssues(contract);
    if (contractIssues.length > 0) {
      issues.push(...contractIssues);
      continue;
    }
    const values = {
      id: readOptionalScalar(contract, "id") ?? "",
      skill: readOptionalScalar(contract, "skill") ?? "",
      summary: readOptionalScalar(contract, "summary") ?? "",
      user_invocable: readOptionalScalar(contract, "user_invocable") ?? "",
    };
    if (!values.id || !values.skill || !values.summary || !values.user_invocable) {
      issues.push({
        code: "projection.contract_invalid",
        severity: "error",
        message: "Command contract requires id, skill, user_invocable, and summary.",
        path,
      });
      continue;
    }
    if (values.user_invocable !== "true" && values.user_invocable !== "false") {
      issues.push({
        code: "projection.contract_invalid",
        severity: "error",
        message: "Command contract user_invocable must be exactly true or false.",
        path,
      });
    }
    const expectedId = file.replace(/\.command\.yaml$/, "");
    if (values.id !== expectedId) {
      issues.push({
        code: "projection.contract_invalid",
        severity: "error",
        message: "Command contract id must match file basename.",
        path,
      });
    }
    if (seenIds.has(values.id)) {
      issues.push({
        code: "projection.contract_invalid",
        severity: "error",
        message: "Command contract id must be unique.",
        path,
      });
    }
    seenIds.add(values.id);
    commands.push({
      id: values.id,
      skill: values.skill,
      userInvocable: values.user_invocable as "true" | "false",
      summary: values.summary,
    });
  }
  for (const requiredId of COMMAND_INDEX_ORDER) {
    if (seenIds.has(requiredId)) continue;
    issues.push({
      code: "projection.contract_invalid",
      severity: "error",
      message: "Required command contract is missing.",
      path: `.ai/core/commands/${requiredId}.command.yaml`,
    });
  }
  if (issues.length > 0) return { ok: false, issues };
  return {
    ok: true,
    value: commands
      .filter((command) => command.userInvocable === "true")
      .sort((left, right) => commandOrder(left.id) - commandOrder(right.id)),
    issues: [],
  };
}

function parseYamlStringList(content: string, path: string, key: string): AiCoreResult<string[]> {
  const contract = parseYamlContract(content, path);
  const issues = yamlIssues(contract);
  if (issues.length > 0) return { ok: false, issues };
  return { ok: true, value: readOptionalStringList(contract, key), issues: [] };
}

function commandOrder(id: string): number {
  const index = COMMAND_INDEX_ORDER.indexOf(id);
  return index === -1 ? Number.MAX_SAFE_INTEGER : index;
}

