type IndexEntry = {
  command: string;
  skill: string;
  outputs: string[];
  workflows: string[];
  agents: string[];
  prompts: string[];
  plugins: string[];
};

function loadSkillOutputs(coreRoot: string, skillName: string): string[] {
  const skillFile = join(coreRoot, "skills", skillName, "skill.yaml");
  if (!existsSync(skillFile)) return [];
  const text = readFileSync(skillFile, "utf8");
  const parsed = parseProductSkillContract(text, `.ai/core/skills/${skillName}/skill.yaml`);
  return parsed.ok ? (parsed.value?.outputs ?? []) : [];
}

function buildIndexEntries(
  coreRoot: string,
  commands: CommandContract[],
  callGraphs: Map<string, SkillCallGraph>,
): IndexEntry[] {
  return commands.map((cmd) => {
    const skillName = stripSkillVersion(cmd.skill);
    const callGraph = callGraphs.get(skillName);
    return {
      command: cmd.id,
      skill: skillName,
      outputs: loadSkillOutputs(coreRoot, skillName),
      workflows: callGraph?.downstreamWorkflows ?? [],
      agents: callGraph?.downstreamAgents ?? [],
      prompts: callGraph?.downstreamPrompts ?? [],
      plugins: callGraph?.downstreamPlugins ?? [],
    };
  });
}

function renderIndexDoc(entries: IndexEntry[]): string {
  const headerSource = JSON.stringify(entries);
  const rows = entries.map((entry) => {
    const cells = [
      `/${entry.command}`,
      entry.skill,
      entry.workflows.join(", ") || "-",
      entry.agents.join(", ") || "-",
      entry.prompts.join(", ") || "-",
      entry.plugins.join(", ") || "-",
      entry.outputs.join(", ") || "-",
    ].map(escapeMarkdownTableCell);
    return `| ${cells.join(" | ")} |`;
  });
  return [
    "# kata 命令调用图",
    "",
    generatedHeader(headerSource).trimEnd(),
    "",
    "每行映射：command → skill → workflow → 下游 agents/prompts/plugins → 输出。冷启动时优先读取本表，无需遍历 commands/。",
    "",
    "| Command | Skill | Workflow | Agents | Prompts | Plugins | Outputs |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

